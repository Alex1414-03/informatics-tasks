# Задача 7. Прайс-лист строительных материалов

prices = {
    "Кирпич": 12.50,
    "Цемент": 450.00,
    "Песок": 800.00,
    "Арматура": 48000.00,
    "Бетон": 4200.00,
}

# Добавляем два материала, повышаем цену одного на 10% и удаляем один.
prices["Щебень"] = 950.00
prices["Гипсокартон"] = 620.00
prices["Цемент"] *= 1.10
del prices["Песок"]

average_price = sum(prices.values()) / len(prices)

print("=== ПРАЙС-ЛИСТ МАТЕРИАЛОВ ===")
for material, price in prices.items():
    print(f"{material:<15} {price:>10.2f} руб.")
print("-" * 30)
print(f"Средняя цена: {average_price:.2f} руб.")
