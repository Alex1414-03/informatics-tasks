materials = ["Кирпич", "Цемент", "Песок", "Арматура", "Бетон"]

print("=== КАТАЛОГ МАТЕРИАЛОВ ===")
print(f"Исходный список: {materials}")
print(f"Первый материал: {materials[0]}")
print(f"Последний материал: {materials[-1]}")
print(f"Средний элемент: {materials[len(materials) // 2]}")

# Добавляем два материала в конец списка.
materials.extend(["Щебень", "Гипсокартон"])
# Удаляем второй элемент по условию задания.
removed_material = materials.pop(1)

print(f"Удалённый материал: {removed_material}")
print(f"Итоговый список: {materials}")
print(f"Количество материалов: {len(materials)}")
