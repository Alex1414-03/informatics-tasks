# Задача 6. Каталог материалов
# Работаем со списком: индексация, срезы, добавление и удаление.

materials = ["Кирпич", "Цемент", "Песок", "Арматура", "Бетон"]

print("=== ИСХОДНЫЙ КАТАЛОГ ===")
print(materials)
print(f"Первый материал: {materials[0]}")
print(f"Последний материал: {materials[-1]}")
print(f"Средние элементы: {materials[1:4]}")

# Добавляем два материала и удаляем второй элемент списка.
materials.extend(["Гипсокартон", "Утеплитель"])
del materials[1]

print()
print("=== ИТОГОВЫЙ КАТАЛОГ ===")
print(materials)
print(f"Количество материалов: {len(materials)}")
