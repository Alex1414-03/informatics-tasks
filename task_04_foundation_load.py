days = {
    1: "Понедельник",
    2: "Вторник",
    3: "Среда",
    4: "Четверг",
    5: "Пятница",
    6: "Суббота",
    7: "Воскресенье",
}

try:
    day_number = int(input("Введите номер дня недели (1–7): "))
except ValueError:
    print("Ошибка: необходимо ввести целое число от 1 до 7.")
else:
    if day_number not in days:
        print("Ошибка: номер дня должен быть от 1 до 7.")
    else:
        day_name = days[day_number]
        is_workday = day_number <= 5

        print("=== РАБОЧИЙ ГРАФИК ===")
        print(f"День: {day_name}")
        print(f"Режим: {'Рабочий день' if is_workday else 'Выходной'}")
        print(f"Расписание: {'8:00 — начало смены' if is_workday else 'Отдых'}")
